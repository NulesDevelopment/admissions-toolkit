export function categoryApplicantIdentity(person: {
  personId?: string
  email?: string
  phone?: string
  personName?: string
}) {
  const personId = String(person.personId || '').trim()
  if (personId) return `person:${personId}`

  const email = String(person.email || '').trim().toLocaleLowerCase('uk')
  if (email) return `email:${email}`

  const phone = String(person.phone || '').replace(/\D+/g, '')
  if (phone) return `phone:${phone}`

  return [
    'fallback',
    String(person.personName || '').trim().toLocaleLowerCase('uk'),
  ].join(':')
}

export function countUniqueCategoryApplicants(
  groups: { applicants?: { personId?: string; email?: string; phone?: string; personName?: string }[] }[],
) {
  const identities = new Set<string>()
  for (const group of groups) {
    for (const person of group.applicants || []) {
      identities.add(categoryApplicantIdentity(person))
    }
  }
  return identities.size
}
